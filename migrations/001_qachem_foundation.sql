-- QACHEM minimal runtime schema.
-- Master/reference data is stored in data/qachem_master.json.

CREATE TABLE IF NOT EXISTS m_user (
  Badge INT NOT NULL,
  Name VARCHAR(160) NULL,
  Password VARCHAR(255) NULL,
  Level INT NOT NULL DEFAULT 1,
  PRIMARY KEY (Badge),
  UNIQUE KEY Badge_UNIQUE (Badge)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS t_qc_inspection (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  inspection_no VARCHAR(40) NOT NULL,
  inspection_type ENUM('INCOMING','INPROCESS','RETURN') NOT NULL,
  spec_type ENUM('IQS','QS','INCOMING') NOT NULL,
  entity_type ENUM('PRODUCT','RAW_MATERIAL') NOT NULL,
  entity_id INT UNSIGNED NOT NULL,
  spec_profile_id BIGINT UNSIGNED NULL,
  chemical_name VARCHAR(200) NOT NULL,
  batch_no VARCHAR(100) NULL,
  plant VARCHAR(30) NULL,
  factory VARCHAR(30) NULL,
  supplier VARCHAR(220) NULL,
  sampling_location VARCHAR(80) NULL,
  tank_no VARCHAR(80) NULL,
  coa_reference VARCHAR(100) NULL,
  manufacturing_date DATE NULL,
  received_date DATE NULL,
  expiry_date DATE NULL,
  inspection_at DATETIME NOT NULL,
  packaging_condition VARCHAR(30) NULL,
  status ENUM('DRAFT','SUBMITTED','PENDING VERIFICATION','VERIFIED','FAILED','HOLD','REJECTED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
  overall_disposition VARCHAR(40) NULL,
  proposed_disposition VARCHAR(40) NULL,
  final_disposition VARCHAR(40) NULL,
  tested_by_badge VARCHAR(60) NULL,
  tested_by_name VARCHAR(160) NULL,
  verified_by_badge VARCHAR(60) NULL,
  verified_by_name VARCHAR(160) NULL,
  submitted_at DATETIME NULL,
  verified_at DATETIME NULL,
  remarks TEXT NULL,
  created_by_badge VARCHAR(60) NOT NULL,
  created_by_name VARCHAR(160) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY inspection_no (inspection_no),
  KEY idx_qc_inspection_type_date (inspection_type, inspection_at),
  KEY idx_qc_inspection_status (status),
  KEY idx_qc_inspection_batch (batch_no),
  KEY idx_qc_inspection_profile (spec_profile_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS t_qc_result (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  inspection_id BIGINT UNSIGNED NOT NULL,
  spec_rule_id BIGINT UNSIGNED NULL,
  parameter_code VARCHAR(40) NOT NULL,
  parameter_name VARCHAR(160) NOT NULL,
  result_value DECIMAL(18,6) NULL,
  result_text TEXT NULL,
  unit VARCHAR(40) NULL,
  disposition VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  attempt_no TINYINT UNSIGNED NOT NULL DEFAULT 1,
  raw_input_json LONGTEXT NULL,
  created_by_badge VARCHAR(60) NOT NULL,
  created_by_name VARCHAR(160) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_qc_result_inspection (inspection_id, attempt_no),
  KEY idx_qc_result_rule (spec_rule_id),
  CONSTRAINT fk_qc_result_inspection FOREIGN KEY (inspection_id) REFERENCES t_qc_inspection(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS t_qc_attachment (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  entity_type VARCHAR(40) NOT NULL,
  entity_id BIGINT UNSIGNED NOT NULL,
  attachment_category VARCHAR(40) NULL,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  file_size BIGINT UNSIGNED NOT NULL,
  uploaded_by_badge VARCHAR(60) NOT NULL,
  uploaded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_qc_attachment (entity_type, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS t_qc_sealing (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  sealing_no VARCHAR(40) NOT NULL,
  seal_date DATE NOT NULL,
  chemical_name VARCHAR(200) NOT NULL,
  batch_no VARCHAR(100) NOT NULL,
  destination_factory VARCHAR(30) NULL,
  packaging_no VARCHAR(255) NULL,
  packaging_type VARCHAR(30) NULL,
  quantity DECIMAL(18,3) NULL,
  coa_confirmed TINYINT(1) NOT NULL DEFAULT 0,
  seal_numbers TEXT NULL,
  label_status VARCHAR(20) NULL,
  appearance_status VARCHAR(20) NULL,
  cleanliness_status VARCHAR(20) NULL,
  sealed_status VARCHAR(20) NULL,
  cable_tie_status VARCHAR(20) NULL,
  disposition VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  inspected_by VARCHAR(160) NULL,
  remarks TEXT NULL,
  created_by_badge VARCHAR(60) NOT NULL,
  created_by_name VARCHAR(160) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY sealing_no (sealing_no),
  KEY idx_qc_sealing_date (seal_date),
  KEY idx_qc_sealing_batch (batch_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS t_qc_coa (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  coa_no VARCHAR(50) NOT NULL,
  inspection_id BIGINT UNSIGNED NOT NULL,
  qs_profile_id BIGINT UNSIGNED NULL,
  customer_factory VARCHAR(30) NULL,
  customer_name VARCHAR(200) NULL,
  po_no VARCHAR(100) NULL,
  packaging_no VARCHAR(255) NULL,
  remarks TEXT NULL,
  generated_by_badge VARCHAR(60) NOT NULL,
  generated_by_name VARCHAR(160) NOT NULL,
  generated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY coa_no (coa_no),
  KEY idx_qc_coa_inspection (inspection_id),
  KEY idx_qc_coa_qs_profile (qs_profile_id),
  CONSTRAINT fk_qc_coa_inspection FOREIGN KEY (inspection_id) REFERENCES t_qc_inspection(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
