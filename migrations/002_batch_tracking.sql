CREATE TABLE IF NOT EXISTS t_qc_inprocess_batch (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  plant VARCHAR(30) NOT NULL,
  inspection_at DATETIME NOT NULL,
  location_id INT UNSIGNED NOT NULL,
  product_id INT UNSIGNED NOT NULL,
  tank VARCHAR(80) NOT NULL,
  batch_no VARCHAR(100) NOT NULL,
  preset_json LONGTEXT NULL,
  created_by_badge VARCHAR(60) NOT NULL,
  modified_by_name VARCHAR(160) NOT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY batch_context (plant,inspection_at,location_id,product_id,created_by_badge),
  KEY batch_number (batch_no,product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS t_qc_tracking (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  tracking_no VARCHAR(50) NOT NULL UNIQUE,
  source_batch_id BIGINT UNSIGNED NULL,
  source_inspection_id BIGINT UNSIGNED NULL,
  planned_batch_no VARCHAR(100) NULL,
  plant VARCHAR(30) NULL,
  product_id INT UNSIGNED NULL,
  chemical_name VARCHAR(200) NULL,
  batch_no VARCHAR(100) NULL,
  source_inspection_at DATETIME NULL,
  source_tank VARCHAR(80) NULL,
  source_badge VARCHAR(60) NULL,
  manufacturing_date DATE NOT NULL,
  factory VARCHAR(30) NOT NULL,
  po_no VARCHAR(100) NOT NULL DEFAULT '',
  packaging_no VARCHAR(255) NOT NULL DEFAULT '',
  remark TEXT NULL,
  testing_date DATE NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'SAVED',
  details_json LONGTEXT NOT NULL,
  snapshot_json LONGTEXT NULL,
  verified_by_badge VARCHAR(60) NULL,
  verified_by_name VARCHAR(160) NULL,
  verified_at DATETIME NULL,
  coa_id BIGINT UNSIGNED NULL,
  coa_revision INT UNSIGNED NOT NULL DEFAULT 0,
  created_by_badge VARCHAR(60) NOT NULL,
  created_by_name VARCHAR(160) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY tracking_batch (batch_no,product_id),
  KEY tracking_source_batch (source_batch_id),
  KEY tracking_source_inspection (source_inspection_id),
  KEY tracking_date (manufacturing_date,factory)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
